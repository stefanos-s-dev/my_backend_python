import pandas as pd
import sqlite3

# 1. Διαβάζουμε το Excel
print("Διαβάζω το αρχείο ΕΥΑΓΓΕΛΙΖΟΜΕΝΟΙ.xlsx...")
# Χρησιμοποιούμε το pandas για να διαβάσουμε το αρχείο. Το df σημαίνει DataFrame, σαν ένας ψηφιακός πίνακας.
df = pd.read_excel('ΕΥΑΓΓΕΛΙΖΟΜΕΝΟΙ.xlsx')

# Επειδή κάποιες στήλες μπορεί να έχουν κενά (NaN), τα μετατρέπουμε σε άδεια strings για να μην "χτυπήσει" η βάση.
df = df.fillna('') 

# 2. Συνδεόμαστε στη Βάση Δεδομένων
print("Δημιουργώ τη βάση δεδομένων...")
# Αν δεν υπάρχει το αρχείο 'app.db', θα το φτιάξει τώρα!
conn = sqlite3.connect('app.db') 

# 3. Μεταφέρουμε τα δεδομένα στη Βάση
print("Μεταφέρω τα δεδομένα...")
# Το pandas παίρνει όλο το Excel (df) και το σώζει ως έναν πίνακα (table) με το όνομα 'people' μέσα στη βάση.
# Το if_exists='replace' σημαίνει ότι αν το τρέξεις 2η φορά, θα σβήσει τα παλιά και θα βάλει τα καινούργια.
df.to_sql('people', conn, if_exists='replace', index=False)

# 4. Κλείνουμε τη σύνδεση
conn.close()

print("Η βάση δημιουργήθηκε με επιτυχία στο αρχείο app.db!")